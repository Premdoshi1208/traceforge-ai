"""A narrow syntax policy for candidate fixture repairs, not a general sandbox."""
from __future__ import annotations

import ast
import difflib
import subprocess
import tempfile
from pathlib import Path

from incident_lab.scenarios import get_scenario, scenario_source

MAX_SOURCE_BYTES = 8_192
ALLOWED_NODES = (
    ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.arguments, ast.arg,
    ast.Return, ast.Expr, ast.Constant, ast.Name, ast.Load, ast.Store,
    ast.Assign, ast.AugAssign, ast.BinOp, ast.UnaryOp, ast.BoolOp, ast.Compare,
    ast.If, ast.IfExp, ast.While, ast.For, ast.Break, ast.Continue, ast.Pass,
    ast.Try, ast.ExceptHandler, ast.Raise, ast.Call, ast.keyword, ast.Await,
    ast.Subscript, ast.Slice, ast.List, ast.Tuple, ast.Dict,
    ast.Add, ast.Sub, ast.Mult, ast.Div, ast.FloorDiv, ast.Mod,
    ast.UAdd, ast.USub, ast.Not, ast.And, ast.Or,
    ast.Eq, ast.NotEq, ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.In, ast.NotIn, ast.Is, ast.IsNot,
)
SAFE_CALLS = {"round", "float", "int", "min", "max", "abs", "len", "range", "ValueError", "TypeError", "KeyError", "TimeoutError", "send"}
SAFE_LOCALS = {"attempt", "attempts", "available", "stock", "rate", "discount", "total", "amount", "value", "result", "error", "exc", "i"}


def validate_patch(scenario_id: str, source: str) -> dict[str, str]:
    scenario = get_scenario(scenario_id)
    if not isinstance(source, str) or not source.strip() or len(source.encode()) > MAX_SOURCE_BYTES:
        raise ValueError("Candidate source must be nonempty and at most 8192 bytes")
    try:
        tree = ast.parse(source)
        original_tree = ast.parse(scenario_source(scenario_id))
    except (SyntaxError, RecursionError) as exc:
        raise ValueError("Candidate source is not valid Python") from exc
    if len(tree.body) != 1 or not isinstance(tree.body[0], (ast.FunctionDef, ast.AsyncFunctionDef)):
        raise ValueError("Only the existing fixture function may be edited")
    fn = tree.body[0]
    original = original_tree.body[0]
    if type(fn) is not type(original) or fn.name != original.name or ast.dump(fn.args) != ast.dump(original.args):
        raise ValueError("Fixture function name, type and signature must remain unchanged")
    if fn.decorator_list or fn.returns or getattr(fn, "type_params", []):
        raise ValueError("Decorators, annotations and type parameters are forbidden")
    allowed_names = {arg.arg for arg in original.args.args} | SAFE_CALLS | SAFE_LOCALS
    nodes = list(ast.walk(tree))
    if len(nodes) > 600:
        raise ValueError("Candidate exceeds the syntax complexity budget")
    for node in nodes:
        if not isinstance(node, ALLOWED_NODES):
            raise ValueError(f"Forbidden Python syntax: {type(node).__name__}")
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node is not fn:
            raise ValueError("Nested functions are forbidden")
        if isinstance(node, ast.Name) and (node.id not in allowed_names or "__" in node.id):
            raise ValueError(f"Identifier is outside fixture policy: {node.id[:60]}")
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store) and node.id in SAFE_CALLS:
            raise ValueError("Safe function bindings may not be replaced")
        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name) or node.func.id not in SAFE_CALLS:
                raise ValueError("Only explicitly allowlisted functions may be called")
            if any(keyword.arg is None for keyword in node.keywords):
                raise ValueError("Dynamic keyword expansion is forbidden")
        if isinstance(node, ast.Constant):
            if isinstance(node.value, (bytes, complex)) or isinstance(node.value, str) and len(node.value) > 512:
                raise ValueError("Constant exceeds fixture policy")
            if isinstance(node.value, (int, float)) and abs(node.value) > 1_000_000:
                raise ValueError("Numeric constant exceeds fixture policy")
        if isinstance(node, ast.ExceptHandler) and node.name and node.name not in SAFE_LOCALS:
            raise ValueError("Exception binding is outside fixture policy")
    # No execution occurs here. The diff is generated by Git when it is available.
    before = scenario_source(scenario_id)
    after = source.rstrip() + "\n"
    path = scenario["path"]
    with tempfile.TemporaryDirectory(prefix="traceforge-diff-") as directory:
        root = Path(directory)
        (root / "before.py").write_text(before)
        (root / "after.py").write_text(after)
        try:
            result = subprocess.run(["git", "--no-pager", "diff", "--no-index", "--no-ext-diff", "--", "before.py", "after.py"], cwd=root, capture_output=True, text=True, timeout=3, env={"PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin", "HOME": directory, "GIT_CONFIG_NOSYSTEM": "1"})
            if result.returncode not in (0, 1):
                raise ValueError("Git diff could not be generated")
            diff = result.stdout.replace("a/before.py", f"a/{path}").replace("b/after.py", f"b/{path}")
        except FileNotFoundError:
            diff = "".join(difflib.unified_diff(before.splitlines(True), after.splitlines(True), fromfile=f"a/{path}", tofile=f"b/{path}"))
    return {"path": path, "before": before, "after": after, "diff": diff}
